// Helper Functions
export function getAllProducts(): Product[] {
  return PRODUCTS;
}

export function getProductByCode(category: string, code: string): Product | undefined {
  const normCat = category.toLowerCase().trim();
  const directCode = code.toLowerCase().trim();
  const dashCode = directCode.startsWith("t") && !directCode.includes("-") ? directCode.replace(/^t/, "t-") : directCode;
  
  return PRODUCTS.find((p) => {
    const catMatch = p.category.toLowerCase() === normCat || (p.secondaryCategories && p.secondaryCategories.includes(normCat as ProductCategory));
    const codeMatch = p.code.toLowerCase() === directCode || p.code.toLowerCase() === dashCode || (p.sku && p.sku.toLowerCase() === directCode) || p.id.toLowerCase() === directCode;
    return catMatch && codeMatch;
  }) || PRODUCTS.find((p) => p.code.toLowerCase() === directCode || p.code.toLowerCase() === dashCode || (p.sku && p.sku.toLowerCase() === directCode) || p.id.toLowerCase() === directCode);
}

export function getProductById(id: string): Product | undefined {
  const normId = id.toLowerCase().trim();
  return PRODUCTS.find((p) => p.id.toLowerCase() === normId || p.code.toLowerCase() === normId || (p.sku && p.sku.toLowerCase() === normId));
}

export function getProductsByCategory(category: ProductCategory | "all"): Product[] {
  if (category === "all") return PRODUCTS;
  return PRODUCTS.filter((p) => p.category === category || (p.secondaryCategories && p.secondaryCategories.includes(category)));
}

export function getCategoryMeta(category: ProductCategory): ProductCategoryMeta | undefined {
  return PRODUCT_CATEGORIES.find((c) => c.id === category);
}
